const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const planner = fs.readFileSync(path.join(root, 'ops/outreach-control/outreachPlanner.js'), 'utf8')
const routePatch = fs.readFileSync(path.join(root, 'ops/outreach-control/20261011_crm_auto_prepare.patch'), 'utf8')
const migration = fs.readFileSync(path.join(root, 'ops/outreach-control/20261011_outreach_auto_settings.sql'), 'utf8')

assert.match(planner, /OUTREACH_ACCOUNT_INTERVAL_MS = \(24 \* 60 \+ 15\) \* 60_000/)
assert.match(planner, /AUTO_DAILY_MINUTES = 16/)
assert.doesNotMatch(planner, /AUTO_DAILY_MINUTES_MAX|randomInt\(AUTO_DAILY_MINUTES/)
assert.match(planner, /spreadMinutes = AUTO_DAILY_MINUTES/)
assert.match(planner, /intervalMinutes: \{ min: AUTO_DAILY_MINUTES, max: AUTO_DAILY_MINUTES \}/)
assert.match(planner, /async function autoPrepareAccount/)
assert.match(planner, /advanceCursor: false/)
assert.match(planner, /excludedPhones/)
assert.match(planner, /async function recheckAndLockPlanEntries/)
assert.match(planner, /insufficient_eligible_contacts/)
assert.match(planner, /await commitPoolCursorForPlan\(planId\)/)
assert.match(routePatch, /POST|router\.post\('\/outreach\/accounts\/:accountId\/auto-prepare'/)
assert.match(migration, /outreach_auto_base_count/)
assert.match(migration, /outreach_auto_message/)

const autoStart = planner.indexOf('async function autoPrepareAccount')
const reservationStart = planner.indexOf('// ── Reservation', autoStart)
const autoBody = planner.slice(autoStart, reservationStart)
assert.doesNotMatch(autoBody, /tryReserve|commitPoolCursorForPlan|armed\s*=\s*TRUE/)
console.log('outreach auto-prepare contract passed')
